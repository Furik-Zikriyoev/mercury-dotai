import { heroList, num, str } from './validate.js';

const heroLine = (list) => list.map((h) => `${h.name} WR:${h.wr}% (${h.games} игр)`).join(', ') || 'нет';

// Промпты разового анализа. Все значения из запроса проходят через str/num/heroList
export function analyzePrompt(type, raw) {
  const d = raw && typeof raw === 'object' ? raw : {};

  if (type === 'stats') {
    return `Ты — эксперт по Dota 2. Проанализируй статистику игрока и дай развёрнутый анализ на русском языке.

Данные игрока:
- Винрейт: ${str(d.winrate, 8)}%
- KDA: ${str(d.kda, 12)}
- Матчей: ${num(d.totalMatches, 0, 1e6)}
- GPM: ${num(d.gpm, 0, 5000)}, XPM: ${num(d.xpm, 0, 5000)}
- Часов в игре: ${num(d.hours, 0, 1e6)}
- Макс. винстрик: ${num(d.maxWinStreak, 0, 1e4)}, Макс. лузстрик: ${num(d.maxLoseStreak, 0, 1e4)}
- Самое активное время игры: ${num(d.peakHour, 0, 23)}:00
- Любимые роли: ${str(d.roles, 120)}

Дай анализ в формате:
**Общая оценка:** (2-3 предложения)
**Сильные стороны:** (список)
**Проблемные места:** (список)
**Психологический профиль:** (анализ по времени игры и паттернам)
**Рекомендации:** (конкретные советы как улучшить игру)`;
  }

  if (type === 'heroes') {
    return `Ты — профессиональный Dota 2 коуч. Проанализируй пул героев. Обращайся на "ты". Без воды.

ДАННЫЕ:
Всего героев: ${num(d.totalHeroes, 0, 300)}
Сильные (WR >55%, 5+ игр): ${heroLine(heroList(d.good, 10))}
Средние (WR 45-55%, 3+ игр): ${heroLine(heroList(d.avg, 10))}
Проблемные (WR <45%, 5+ игр): ${heroLine(heroList(d.bad, 10))}

ВАЖНО: разбери КАЖДОГО героя из списка выше — не пропускай ни одного.

СТРОГО СЛЕДУЙ ФОРМАТУ — повторяй блок для каждого героя:

💚 СИЛЬНЫЕ ГЕРОИ

(для каждого сильного героя по блоку:)
[Имя] — WR X%
Почему работает:
[2-3 предложения конкретно]
Как развивать:
1. [конкретный совет]
2. [конкретный совет]
3. [конкретный совет]

---

⚡ СРЕДНИЕ ГЕРОИ

(для каждого среднего героя по блоку:)
[Имя] — WR X%
Что мешает расти:
[конкретная причина]
Как улучшить:
1. [конкретное действие]
2. [конкретное действие]
3. [конкретное действие]

---

💀 ПРОБЛЕМНЫЕ ГЕРОИ

(для каждого проблемного героя по блоку:)
[Имя] — WR X%
Главная проблема:
[конкретная механическая или стратегическая проблема]
Конкретное решение:
1. [конкретное действие]
2. [конкретное действие]
3. [конкретное действие]

---

📋 ИТОГ ПО ПУЛУ

На чём фокусироваться:
1. [пункт]
2. [пункт]
3. [пункт]
Кого убрать из пула:
[Имя] — [причина]
Кого попробовать:
[Имя] — [почему подойдёт]`;
  }

  if (type === 'match') {
    const hero = str(d.hero, 40);
    const win = d.result === 'Победа';
    return `Ты — эксперт по Dota 2. Проанализируй матч и дай детальный разбор на русском языке.

Герой: ${hero}
Результат: ${win ? 'Победа' : 'Поражение'}
KDA: ${num(d.kills, 0, 200)}/${num(d.deaths, 0, 200)}/${num(d.assists, 0, 200)}
GPM: ${num(d.gpm, 0, 5000)}, XPM: ${num(d.xpm, 0, 5000)}
Урон по героям: ${str(d.damage, 16)}
Нетворс: ${str(d.networth, 16)}
Длительность: ${str(d.duration, 12)}
Роль: ${str(d.role, 30)}

Дай анализ в формате:
**Общая оценка матча:** (2-3 предложения)
${
  win
    ? '**Что сыграло на победу:** (ключевые факторы)\n**Что можно улучшить даже в победном матче:** (конкретные моменты)'
    : '**Причины поражения:** (конкретные факторы)\n**Что нужно было сделать иначе:** (конкретные советы)'
}
**Советы по герою ${hero}:** (как играть лучше на этом герое)
**Итог:** (1-2 предложения)`;
  }

  return null;
}

// Данные игрока для персональных советов в чате
export function playerContextBlock(raw) {
  if (!raw || typeof raw !== 'object') return '';
  return `\n\nДАННЫЕ ИГРОКА (для персонализированных советов):
- Winrate: ${str(raw.winrate, 8)}%
- KDA: ${str(raw.kda, 12)}
- Матчей: ${num(raw.totalMatches, 0, 1e6)}
- GPM: ${num(raw.gpm, 0, 5000)}, XPM: ${num(raw.xpm, 0, 5000)}
- Любимые роли: ${str(raw.roles, 120)}
- Топ герои: ${str(raw.topHeroes, 200) || 'нет данных'}`;
}

